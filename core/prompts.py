def build_planning_prompt(req_json: str, design_json: str) -> str:
    return f"""Create a short-term MVP execution plan. Output ONLY a JSON object with no markdown.

REQUIREMENTS:
{req_json}

DESIGN:
{design_json}

Output JSON with:
- plan_name: e.g. "MVP Plan"
- tasks: AT LEAST 5-8 items, each with id, title, assigned_agent (Developer/Designer/DBA), priority (high or low)
- risks: 3-5 short risk strings"""


# ---------------------------------------------------------------------------
# Quality / Process Manager
